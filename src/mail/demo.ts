const DEMO = 'demo';

function message(partial: Omit<MailMessage, 'accountId' | 'bcc' | 'labelIds' | 'bodyLoaded' | 'hasAttachments' | 'snippet'> & Partial<Pick<MailMessage, 'labelIds' | 'snippet' | 'hasAttachments'>>): MailMessage {
  const text = partial.text;
  return {
    bcc: [],
    labelIds: partial.labelIds ?? [],
    bodyLoaded: true,
    hasAttachments: partial.hasAttachments ?? (partial.attachments?.length ?? 0) > 0,
    snippet: partial.snippet ?? text.replace(/\s+/g, ' ').trim().slice(0, 160),
    accountId: DEMO,
    ...partial,
  };
}

